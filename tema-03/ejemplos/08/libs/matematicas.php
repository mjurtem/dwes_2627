<?php

/*
    Declaracion de funciones matematicas:
    - sumar: recibe dos numeros enteros y los suma
    - restar: recibe dos numeros enteros y los resta
    - multiplicar: recibe dos numeros enteros y los multiplica
    - dividir: recibe dos numeros enteros y los dividde

*/

function sumar(int $a, int $b) // Llamada  a la función
{
    return $a + $b;
}

function restar(int $a, int $b) // Llamada  a la función
{
    return $a - $b;
}

function multiplicar(int $a, int $b) // Llamada  a la función
{
    return $a * $b;
}

function dividir(int $a, int $b) // Llamada  a la función
{
    return $a / $b;
}
?>